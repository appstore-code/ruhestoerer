/* ── Translation engine ──────────────────────────────────── */

let currentLang = 'de';

function detectLang() {
  const stored = localStorage.getItem('rs_lang');
  if (stored && (stored === 'de' || stored === 'en')) return stored;
  const nav = (navigator.language || 'de').toLowerCase();
  return nav.startsWith('de') ? 'de' : 'en';
}

function applyTranslations(lang) {
  currentLang = lang;
  const t = translations[lang];
  if (!t) return;

  document.documentElement.lang = lang;

  // Apply data-i18n attributes
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = key.split('.').reduce((o, k) => o?.[k], t);
    if (val !== undefined) {
      // Handle newlines
      el.innerHTML = val.replace(/\n/g, '<br>');
    }
  });

  // Apply data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const val = key.split('.').reduce((o, k) => o?.[k], t);
    if (val !== undefined) el.placeholder = val;
  });

  // Update lang toggle buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  // Toggle bilingual content sections
  document.querySelectorAll('.lang-content').forEach(el => {
    el.classList.toggle('active', el.getAttribute('lang') === lang);
  });
}

function setLang(lang) {
  localStorage.setItem('rs_lang', lang);
  applyTranslations(lang);
}

function initI18n() {
  const lang = detectLang();
  applyTranslations(lang);
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => setLang(btn.dataset.lang));
  });
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initI18n);
} else {
  initI18n();
}
